const useColor = process.stdout.isTTY && !process.env.NO_COLOR
const c = {
  dim: (s: string) => (useColor ? `\x1b[2m${s}\x1b[0m` : s),
  bold: (s: string) => (useColor ? `\x1b[1m${s}\x1b[0m` : s),
  green: (s: string) => (useColor ? `\x1b[32m${s}\x1b[0m` : s),
  yellow: (s: string) => (useColor ? `\x1b[33m${s}\x1b[0m` : s),
  red: (s: string) => (useColor ? `\x1b[31m${s}\x1b[0m` : s),
  cyan: (s: string) => (useColor ? `\x1b[36m${s}\x1b[0m` : s),
}

/* -------------------------------- arg parsing ------------------------------ */

type Flags = Record<string, string | boolean>

function parseFlags(args: string[]): Flags {
  const flags: Flags = {}
  for (let i = 0; i < args.length; i++) {
    const arg = args[i]
    if (!arg.startsWith('-')) continue
    const body = arg.replace(/^--?/, '')
    if (body.includes('=')) {
      const [key, ...rest] = body.split('=')
      flags[key] = rest.join('=')
      continue
    }
    const next = args[i + 1]
    if (next && (next === '-' || !next.startsWith('-'))) {
      flags[body] = next
      i++
    } else {
      flags[body] = true
    }
  }
  return flags
}

function str(flags: Flags, key: string, fallback?: string): string | undefined {
  const value = flags[key]
  return typeof value === 'string' ? value : fallback
}

const SITE_MARKER = '.scdocs'

/** True when `parent` is `child` itself or an ancestor of it. */
function containsPath(parent: string, child: string): boolean {
  const rel = relative(parent, child)
  return rel === '' || (!rel.startsWith('..') && !isAbsolute(rel))
}

/** Only an existing scdocs site may be replaced. */
async function isGeneratedSite(dir: string): Promise<boolean> {
  if (existsSync(join(dir, SITE_MARKER))) return true
  try {
    const data = JSON.parse(await readFile(join(dir, 'data.json'), 'utf8')) as {
      generator?: { name?: string }
    }
    return data.generator?.name === 'scdocs'
  } catch {
    return false
  }
}

/**
 * `cmdBuild` deletes `--out` before copying the new site. Guard against the
 * obvious footgun: `--out .` (or an ancestor of the project) must never wipe
 * the project itself, and a non-empty directory may only be replaced if scdocs
 * generated it.
 */
async function assertSafeOutDir(outDir: string, root: string): Promise<void> {
  const resolvedOut = await realpath(outDir).catch(() => outDir)
  const protectedDirs: Array<[string, string]> = [
    ['current directory', process.cwd()],
    ['contracts root', root],
    ['scdocs package', pkgDir],
  ]

  for (const [label, dir] of protectedDirs) {
    const resolvedDir = await realpath(dir).catch(() => dir)
    if (containsPath(resolvedOut, resolvedDir)) {
      throw new Error(
        `Refusing to write docs to ${outDir}: it contains the ${label} (${dir}). ` +
          `Choose a dedicated output directory, e.g. ${join(root, 'scdocs-site')}.`,
      )
    }
  }

  let info
  try {
    info = await stat(outDir)
  } catch {
    return // New directory: safe.
  }
  if (!info.isDirectory()) {
    throw new Error(`Refusing to overwrite ${outDir}: it is not a directory.`)
  }

  const entries = (await readdir(outDir)).filter((entry) => entry !== '.DS_Store')
  if (entries.length === 0) return // Empty directory: safe.
  if (await isGeneratedSite(outDir)) return

  throw new Error(
    `Refusing to overwrite ${outDir}: it is not empty and was not generated by scdocs. ` +
      `Choose a dedicated output directory.`,
  )
}

