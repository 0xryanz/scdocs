/** Works both from `dist/cli.js` and from `src/cli/index.ts` (tsx during dev). */
function findPackageDir(): string {
  let dir = dirname(fileURLToPath(import.meta.url))
  for (let depth = 0; depth < 8; depth++) {
    if (existsSync(join(dir, 'package.json'))) return dir
    const parent = dirname(dir)
    if (parent === dir) break
    dir = parent
  }
  return resolve(dirname(fileURLToPath(import.meta.url)), '..')
}

const pkgDir = findPackageDir()

// `scdocs export --out -` is meant to be piped into head/jq; closing the pipe
// early is normal, not an error worth a stack trace.
process.stdout.on('error', (error: NodeJS.ErrnoException) => {
  if (error.code === 'EPIPE') process.exit(0)
  throw error
})

