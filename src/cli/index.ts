const PRESETS = ['vercel', 'cloudflare', 'gh-pages'] as const
type Preset = (typeof PRESETS)[number]

function boolFlag(flags: Flags, key: string): boolean {
  return flags[key] === true || flags[key] === 'true'
}

function parsePreset(value: string | undefined): Preset | undefined {
  if (!value) return undefined
  if ((PRESETS as readonly string[]).includes(value)) return value as Preset
  throw new Error(`Unknown preset "${value}". Use vercel, cloudflare or gh-pages.`)
}

function assertContracts(bundle: DocsBundle, root: string): void {
  if (bundle.contracts.length > 0) return
  throw new Error(
    bundle.frameworks.length === 0
      ? `No Solidity build artifacts found under ${root}. Point --root at the Foundry project root ` +
          `(the folder containing foundry.toml and out/) or the Hardhat project root ` +
          `(containing artifacts/build-info/).`
      : `No contracts matched the include/exclude rules in the scdocs config.`,
  )
}

function printCoverage(bundle: DocsBundle): void {
  const coverage = coverageOf(bundle)
  console.log(
    c.dim(
      `  docs ${coverage.documented}/${coverage.functions} functions documented ` +
        `(${coverage.percent.toFixed(1)}%)`,
    ),
  )
}

async function applyPreset(dir: string, preset: Preset): Promise<void> {
  const index = await readFile(join(dir, 'index.html'))
  await writeFile(join(dir, '404.html'), index)

  if (preset === 'vercel') {
    const config = {
      cleanUrls: true,
      trailingSlash: false,
      headers: [
        {
          source: '/assets/(.*)',
          headers: [{ key: 'Cache-Control', value: 'public, max-age=31536000, immutable' }],
        },
      ],
    }
    await writeFile(join(dir, 'vercel.json'), `${JSON.stringify(config, null, 2)}\n`)
  }

  if (preset === 'cloudflare') {
    await writeFile(
      join(dir, '_headers'),
      [
        '/assets/*',
        '  Cache-Control: public, max-age=31536000, immutable',
        '/index.html',
        '  Cache-Control: no-cache',
        '/data.json',
        '  Cache-Control: no-cache',
        '',
      ].join('\n'),
    )
  }

  if (preset === 'gh-pages') {
    await writeFile(join(dir, '.nojekyll'), '')
  }
}

async function atomicBuild(
  siteDir: string,
  outDir: string,
  bundle: DocsBundle,
  preset: Preset | undefined,
): Promise<void> {
  await mkdir(dirname(outDir), { recursive: true })
  const temp = `${outDir}.tmp-${process.pid}-${Date.now()}`
  await rmrf(temp)

  try {
    await cp(siteDir, temp, { recursive: true })
    await writeFile(join(temp, SITE_MARKER), 'Generated by scdocs. Safe to delete and rebuild.\n')
    await writeFile(join(temp, 'data.json'), JSON.stringify(bundle, null, 2))
    await writeFile(join(temp, 'openapi.json'), JSON.stringify(toOpenApi(bundle), null, 2))
    await writeFile(join(temp, 'llms.txt'), toLlms(bundle))
    await writeFile(join(temp, 'mcp.json'), `${JSON.stringify(toMcp(bundle), null, 2)}\n`)
    await injectInlineData(temp, bundle)
    if (preset) await applyPreset(temp, preset)

    await rmrf(outDir)
    await rename(temp, outDir)
  } catch (error) {
    await rmrf(temp).catch(() => undefined)
    throw error
  }
}

async function cmdBuild(flags: Flags): Promise<void> {
  const root = resolve(str(flags, 'root', process.cwd())!)
  const outDir = resolve(str(flags, 'out', join(root, 'scdocs-site'))!)
  const preset = parsePreset(str(flags, 'preset'))
  const dryRun = boolFlag(flags, 'dry-run')
  const started = Date.now()

  await assertSafeOutDir(outDir, root)

  const { bundle, warnings } = await buildBundle({ root, config: str(flags, 'config') })
  reportBundle(bundle, warnings)
  assertContracts(bundle, root)
  printCoverage(bundle)

  if (dryRun) {
    console.log(c.bold('\nDry run'))
    console.log(`  root      ${root}`)
    console.log(`  output    ${outDir}`)
    console.log(`  config    ${str(flags, 'config') ?? 'auto-detect'}`)
    console.log(`  contracts ${bundle.contracts.map((contract) => contract.name).join(', ')}`)
    if (bundle.pages?.length) {
      console.log(`  pages     ${bundle.pages.map((page) => page.title).join(', ')}`)
    }
    if (preset) console.log(`  preset    ${preset}`)
    console.log(c.dim('  no files written'))
    return
  }

  const siteDir = await renderSite()
  await atomicBuild(siteDir, outDir, bundle, preset)

  const elapsed = ((Date.now() - started) / 1000).toFixed(1)
  console.log(
    `\n${c.green('✓')} site ${c.dim(`(${elapsed}s)`)} → ${c.cyan(outDir)}`,
  )
  console.log(c.dim(`  serve it with:  scdocs serve --dir ${rel(outDir)}`))
  if (preset) {
    const hints: Record<Preset, string> = {
      vercel: 'Deploy: vercel deploy --prod <dir>',
      cloudflare: 'Deploy: wrangler pages deploy <dir>',
      'gh-pages': 'Deploy: push the folder to a gh-pages branch',
    }
    console.log(c.dim(`  preset ${preset} · ${hints[preset]}`))
  }

  if (flags.open) {
    await openInBrowser(`file://${join(outDir, 'index.html')}`)
  }
}

async function cmdDev(flags: Flags): Promise<void> {
  const root = resolve(str(flags, 'root', process.cwd())!)
  const port = Number(str(flags, 'port', '5173'))
  const host = str(flags, 'host', '127.0.0.1')!
  const configPath = str(flags, 'config')

  let lastWarnings = 0
  const load = async (): Promise<DocsBundle> => {
    const { bundle, warnings } = await buildBundle({ root, config: configPath })
    if (lastWarnings !== warnings.length) {
      reportBundle(bundle, warnings)
      lastWarnings = warnings.length
    }
    return bundle
  }

  await load()

  const { createServer } = await import('vite')
  const server = await createServer({
    root: pkgDir,
    configFile: join(pkgDir, 'vite.config.ts'),
    server: { port, host, strictPort: false, open: Boolean(flags.open) },
    plugins: [
      {
        name: 'scdocs-data',
        configureServer(devServer) {
          devServer.middlewares.use((req, res, next) => {
            const path = (req.url ?? '').split('?')[0]
            if (path !== '/data.json' && path !== '/openapi.json') return next()
            load()
              .then((bundle) => {
                const body = path === '/data.json' ? bundle : toOpenApi(bundle)
                res.setHeader('content-type', 'application/json')
                res.setHeader('cache-control', 'no-store')
                res.end(JSON.stringify(body))
              })
              .catch((error) => {
                res.statusCode = 500
                res.setHeader('content-type', 'application/json')
                res.end(JSON.stringify({ error: String(error?.stack ?? error) }))
              })
          })
        },
      },
    ],
  })

  await server.listen()
  server.printUrls()
  console.log(c.dim('  data.json is regenerated on every request — refresh after rebuilding contracts.'))
}

async function cmdServe(flags: Flags): Promise<void> {
  const dir = resolve(str(flags, 'dir', join(process.cwd(), 'scdocs-site'))!)
  const port = Number(str(flags, 'port', '8080'))
  if (!existsSync(join(dir, 'index.html'))) {
    console.error(c.red(`No index.html in ${dir}. Run "scdocs build" first.`))
    process.exitCode = 1
    return
  }

  const types: Record<string, string> = {
    '.html': 'text/html; charset=utf-8',
    '.js': 'text/javascript; charset=utf-8',
    '.css': 'text/css; charset=utf-8',
    '.json': 'application/json; charset=utf-8',
    '.txt': 'text/plain; charset=utf-8',
    '.svg': 'image/svg+xml',
    '.png': 'image/png',
    '.woff2': 'font/woff2',
    '.webmanifest': 'application/manifest+json',
  }

  createHttpServer(async (req, res) => {
    const urlPath = decodeURIComponent((req.url ?? '/').split('?')[0])
    let filePath = join(dir, urlPath === '/' ? 'index.html' : urlPath)
    if (!filePath.startsWith(dir)) {
      res.statusCode = 403
      res.end('forbidden')
      return
    }
    try {
      if ((await stat(filePath)).isDirectory()) filePath = join(filePath, 'index.html')
    } catch {
      res.statusCode = 404
      res.end('not found')
      return
    }
    try {
      const body = await readFile(filePath)
      res.setHeader('content-type', types[extname(filePath)] ?? 'application/octet-stream')
      res.end(body)
    } catch {
      res.statusCode = 404
      res.end('not found')
    }
  }).listen(port, () => {
    console.log(`${c.green('✓')} serving ${c.cyan(dir)}\n  ${c.cyan(`http://localhost:${port}`)}`)
  })
}

async function cmdOpenApi(flags: Flags): Promise<void> {
  const root = resolve(str(flags, 'root', process.cwd())!)
  const out = resolve(str(flags, 'out', join(root, 'openapi.json'))!)
  const { bundle, warnings } = await buildBundle({ root, config: str(flags, 'config') })
  reportBundle(bundle, warnings)
  await writeFile(out, JSON.stringify(toOpenApi(bundle), null, 2))
  console.log(`${c.green('✓')} openapi.json → ${c.cyan(out)}`)
}

const HARDHAT_CONFIGS = [
  'hardhat.config.ts',
  'hardhat.config.js',
  'hardhat.config.cjs',
  'hardhat.config.mjs',
]

async function cmdInit(flags: Flags): Promise<void> {
  const cwd = resolve(str(flags, 'root', process.cwd())!)
  const force = boolFlag(flags, 'force')

  let contractsRoot: string
  let include: string[]
  let exclude: string[]
  let framework: 'foundry' | 'hardhat'

  if (existsSync(join(cwd, 'foundry.toml'))) {
    contractsRoot = cwd
    framework = 'foundry'
    include = ['src/*']
    exclude = ['src/interfaces/*', 'src/mocks/*', 'test/*', 'script/*']
  } else if (existsSync(join(cwd, 'contracts', 'foundry.toml'))) {
    contractsRoot = join(cwd, 'contracts')
    framework = 'foundry'
    include = ['src/*']
    exclude = ['src/interfaces/*', 'src/mocks/*', 'test/*', 'script/*']
  } else if (HARDHAT_CONFIGS.some((name) => existsSync(join(cwd, name)))) {
    contractsRoot = cwd
    framework = 'hardhat'
    include = ['contracts/*']
    exclude = ['contracts/mocks/*', 'test/*', 'scripts/*']
  } else if (HARDHAT_CONFIGS.some((name) => existsSync(join(cwd, 'contracts', name)))) {
    contractsRoot = join(cwd, 'contracts')
    framework = 'hardhat'
    include = ['contracts/*']
    exclude = ['contracts/mocks/*', 'test/*', 'scripts/*']
  } else {
    throw new Error(
      'No Foundry or Hardhat project found. Run this from the project root, or pass --root <contracts-dir>.',
    )
  }

  const configPath = join(contractsRoot, 'scdocs.config.ts')
  if (existsSync(configPath) && !force) {
    throw new Error(`${configPath} already exists. Use --force to overwrite it.`)
  }

  const title =
    str(flags, 'title') ??
    (await packageTitle(cwd)) ??
    basename(cwd)

  const config = [
    '// Generated by `scdocs init`. Adjust include/exclude to taste.',
    'export default {',
    `  title: ${JSON.stringify(title)},`,
    `  include: [${include.map((item) => JSON.stringify(item)).join(', ')}],`,
    `  exclude: [${exclude.map((item) => JSON.stringify(item)).join(', ')}],`,
    '}',
    '',
  ].join('\n')
  await writeFile(configPath, config)

  await ensureGitignore(cwd)
  const scripts = await ensureDocsScripts(cwd, contractsRoot)

  const relRoot = relative(cwd, contractsRoot) || '.'
  console.log(`${c.green('✓')} wrote ${configPath}`)
  console.log(`${c.dim('  framework')} ${framework}`)
  console.log(`${c.dim('  root     ')} ${contractsRoot}`)
  if (scripts.length) console.log(`${c.dim('  scripts  ')} ${scripts.join(', ')}`)
  console.log(`\n${c.bold('Next')}`)
  console.log(`  1. ${framework === 'foundry' ? 'forge build' : 'npx hardhat compile'}`)
  console.log(`  2. npm run docs:build   ${c.dim(`# scdocs build --root ${relRoot} --out scdocs-site`)}`)
  console.log('  3. npm run docs:serve')
}

async function cmdDoctor(flags: Flags): Promise<void> {
  const root = resolve(str(flags, 'root', process.cwd())!)
  const outDir = resolve(str(flags, 'out', join(root, 'scdocs-site'))!)
  const { bundle, warnings } = await buildBundle({ root, config: str(flags, 'config') })
  reportBundle(bundle, warnings)

  let safe = true
  let unsafeReason: string | undefined
  try {
    await assertSafeOutDir(outDir, root)
  } catch (error) {
    safe = false
    unsafeReason = (error as Error).message
  }

  console.log(`  root      ${root}`)
  console.log(`  output    ${outDir}${safe ? '' : c.yellow(' (unsafe)')}`)
  console.log(`  config    ${str(flags, 'config') ?? 'auto-detect'}`)
  console.log(`  frameworks ${bundle.frameworks.join(' + ') || 'none'}`)
  printCoverage(bundle)
  if (bundle.pages?.length) console.log(`  pages     ${bundle.pages.length}`)
  if (bundle.contracts.length) {
    console.log(`  contracts ${bundle.contracts.map((contract) => contract.name).join(', ')}`)
  }
  if (unsafeReason) console.log(c.yellow(`  ! ${unsafeReason}`))

  if (bundle.contracts.length === 0 || !safe) process.exitCode = 1
}

async function cmdCheck(flags: Flags): Promise<void> {
  const root = resolve(str(flags, 'root', process.cwd())!)
  const json = boolFlag(flags, 'json')
  const { bundle, warnings } = await buildBundle({ root, config: str(flags, 'config') })
  if (!json) reportBundle(bundle, warnings)
  assertContracts(bundle, root)

  const coverage = coverageOf(bundle)
  const baseline = str(flags, 'baseline')
  const writeBaseline = str(flags, 'write-baseline')
  const minCoverageValue = str(flags, 'min-coverage')
  const minCoverage = minCoverageValue === undefined ? undefined : Number(minCoverageValue)

  if (writeBaseline) {
    const path = resolve(writeBaseline)
    await writeFile(path, JSON.stringify(bundle, null, 2))
    console.log(`${c.green('✓')} baseline → ${c.cyan(path)}`)
    return
  }

  if (minCoverage !== undefined && (!Number.isFinite(minCoverage) || minCoverage < 0 || minCoverage > 100)) {
    throw new Error(`Invalid --min-coverage value: ${minCoverageValue}. Use a number from 0 to 100.`)
  }

  let diff
  if (baseline) {
    const path = resolve(baseline)
    const previous = JSON.parse(await readFile(path, 'utf8')) as DocsBundle
    diff = compareBundles(previous, bundle)
  }

  let failed = false
  if (diff) {
    if (!json) {
      console.log(`\n${c.bold('ABI diff')} ${c.dim(`vs ${baseline}`)}`)
      for (const name of diff.contractsAdded) console.log(c.green(`  + contract ${name}`))
      for (const name of diff.contractsRemoved) console.log(c.red(`  - contract ${name}`))
      for (const change of diff.contractsChanged) {
        console.log(`  ${change.contract}`)
        for (const item of change.added) console.log(c.green(`    + ${item}`))
        for (const item of change.removed) console.log(c.red(`    - ${item}`))
        for (const item of change.changed) console.log(c.yellow(`    ~ ${item}`))
      }
      if (!diff.contractsAdded.length && !diff.contractsRemoved.length && !diff.contractsChanged.length) {
        console.log(c.dim('  no ABI changes'))
      }
    }
    failed = failed || hasBreakingChanges(diff)
  }

  if (json) {
    console.log(JSON.stringify({ coverage, diff: diff ?? null }, null, 2))
  } else {
    console.log(
      `\n${c.bold('Docs coverage')} ${coverage.documented}/${coverage.functions} ` +
        `(${coverage.percent.toFixed(1)}%) · ${coverage.undocumented} undocumented`,
    )
  }

  if (
    minCoverage !== undefined &&
    coverage.percent < minCoverage
  ) {
    if (!json) console.log(c.red(`  coverage ${coverage.percent.toFixed(1)}% is below --min-coverage ${minCoverage}%`))
    failed = true
  }
  if (boolFlag(flags, 'fail-on-undocumented') && coverage.undocumented > 0) {
    if (!json) console.log(c.red(`  ${coverage.undocumented} functions have no NatSpec`))
    failed = true
  }
  if (failed) process.exitCode = 1
}

async function cmdExport(flags: Flags): Promise<void> {
  const root = resolve(str(flags, 'root', process.cwd())!)
  const format = str(flags, 'format', 'llms')!
  if (!['llms', 'mcp', 'openapi'].includes(format)) {
    throw new Error(`Unknown export format "${format}". Use llms, mcp or openapi.`)
  }
  const { bundle, warnings } = await buildBundle({ root, config: str(flags, 'config') })
  assertContracts(bundle, root)

  const body =
    format === 'openapi'
      ? `${JSON.stringify(toOpenApi(bundle), null, 2)}\n`
      : format === 'mcp'
        ? `${JSON.stringify(toMcp(bundle), null, 2)}\n`
        : toLlms(bundle)

  const outFlag = str(flags, 'out')
  if (outFlag === '-') {
    process.stdout.write(body)
    return
  }
  reportBundle(bundle, warnings)
  const out = resolve(
    outFlag ?? (format === 'openapi' ? 'openapi.json' : format === 'mcp' ? 'mcp.json' : 'llms.txt'),
  )
  await writeFile(out, body)
  console.log(`${c.green('✓')} ${format} → ${c.cyan(out)}`)
}

async function packageTitle(dir: string): Promise<string | undefined> {
  try {
    const pkg = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8')) as {
      name?: string
    }
    return pkg.name
  } catch {
    return undefined
  }
}

async function ensureGitignore(projectRoot: string): Promise<void> {
  const path = join(projectRoot, '.gitignore')
  let text = ''
  try {
    text = await readFile(path, 'utf8')
  } catch {
    // No .gitignore yet.
  }
  const lines = text.split('\n').map((line) => line.trim())
  if (lines.includes('scdocs-site/') || lines.includes('scdocs-site')) return
  const next = `${text}${text && !text.endsWith('\n') ? '\n' : ''}scdocs-site/\n`
  await writeFile(path, next)
}

async function ensureDocsScripts(
  projectRoot: string,
  contractsRoot: string,
): Promise<string[]> {
  const path = join(projectRoot, 'package.json')
  let pkg: { scripts?: Record<string, string> } & Record<string, unknown>
  try {
    pkg = JSON.parse(await readFile(path, 'utf8'))
  } catch {
    return []
  }
  const scripts = { ...(pkg.scripts ?? {}) }
  const added: string[] = []
  if (!scripts['docs:build']) {
    scripts['docs:build'] = `scdocs build --root ${relative(projectRoot, contractsRoot) || '.'} --out scdocs-site`
    added.push('docs:build')
  }
  if (!scripts['docs:serve']) {
    scripts['docs:serve'] = 'scdocs serve --dir scdocs-site --port 8080'
    added.push('docs:serve')
  }
  if (added.length === 0) return []
  pkg.scripts = scripts
  await writeFile(path, `${JSON.stringify(pkg, null, 2)}\n`)
  return added
}

