async function main(): Promise<void> {
  const [command, ...rest] = process.argv.slice(2)
  const flags = parseFlags(rest)

  try {
    switch (command) {
      case 'build':
        await cmdBuild(flags)
        break
      case 'init':
        await cmdInit(flags)
        break
      case 'doctor':
        await cmdDoctor(flags)
        break
      case 'check':
        await cmdCheck(flags)
        break
      case 'export':
      case 'llms':
      case 'mcp':
        if (command === 'llms') flags.format = 'llms'
        if (command === 'mcp') flags.format = 'mcp'
        await cmdExport(flags)
        break
      case 'dev':
      case 'start':
        await cmdDev(flags)
        break
      case 'serve':
      case 'preview':
        await cmdServe(flags)
        break
      case 'openapi':
        await cmdOpenApi(flags)
        break
      case 'help':
      case '--help':
      case '-h':
      case undefined:
        help()
        break
      default:
        console.error(c.red(`Unknown command: ${command}`))
        help()
        process.exitCode = 1
    }
  } catch (error) {
    console.error(c.red(`\n✗ ${(error as Error)?.message ?? error}`))
    if (process.env.SCDOCS_DEBUG) console.error(error)
    process.exitCode = 1
  }
}

