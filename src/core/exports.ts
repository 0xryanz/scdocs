import type { DocsBundle, FunctionDoc } from '../shared/types.js'

/** A compact text index for LLMs and documentation search. */
export function toLlms(bundle: DocsBundle): string {
  const lines: string[] = [
    `# ${bundle.title}`,
    bundle.description ?? '',
    '',
    `Generated by ${bundle.generator.name} ${bundle.generator.version} · abi ${bundle.abiHash}`,
    '',
    '## Contracts',
    '',
  ]

  for (const contract of bundle.contracts) {
    lines.push(`### ${contract.name}`)
    if (contract.title && contract.title !== contract.name) lines.push(`Title: ${contract.title}`)
    lines.push(`Source: ${contract.file}`)
    if (contract.summary) lines.push('', contract.summary)
    if (contract.description) lines.push('', contract.description)

    const deployments = deploymentsOf(bundle, contract.id)
    if (deployments.length > 0) {
      lines.push('', 'Deployments:')
      for (const deployment of deployments) {
        lines.push(`- ${deployment.chainName} (${deployment.chainId}): ${deployment.address}`)
      }
    }

    lines.push('', 'Functions:')
    for (const fn of contract.functions) {
      lines.push(`- ${fn.signature} [${isRead(fn) ? 'read' : 'write'}]${fn.summary ? ` — ${fn.summary}` : ''}`)
    }
    if (contract.events.length > 0) {
      lines.push('', `Events: ${contract.events.map((event) => event.signature).join(', ')}`)
    }
    if (contract.errors.length > 0) {
      lines.push(`Errors: ${contract.errors.map((error) => error.signature).join(', ')}`)
    }
    lines.push('')
  }

  if (bundle.pages?.length) {
    lines.push('## Pages', '')
    for (const page of bundle.pages) {
      lines.push(`- ${page.title}${page.description ? ` — ${page.description}` : ''}`)
    }
  }

  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trim()}\n`
}

/**
 * A provider-neutral tool manifest. It is intentionally a static export: an
 * MCP server or agent runtime can turn each function into a tool without
 * needing access to the compiler or the docs UI.
 */
export function toMcp(bundle: DocsBundle): Record<string, unknown> {
  const tools = bundle.contracts.flatMap((contract) =>
    contract.functions.map((fn) => {
      const deployments = deploymentsOf(bundle, contract.id).map((deployment) => ({
        chainId: deployment.chainId,
        address: deployment.address,
      }))
      const properties: Record<string, unknown> = {}
      const required: string[] = []
      fn.inputs.forEach((input, index) => {
        const key = input.name || `arg${index}`
        properties[key] = input.schema
        required.push(key)
      })

      return {
        name: toolName(contract.name, fn),
        description: functionDescription(contract.name, fn),
        inputSchema: {
          type: 'object',
          properties,
          required,
          additionalProperties: false,
        },
        annotations: {
          readOnlyHint: isRead(fn),
          destructiveHint: !isRead(fn),
        },
        _meta: {
          contract: contract.name,
          source: contract.file,
          signature: fn.signature,
          selector: fn.selector,
          deployments,
        },
      }
    }),
  )

  return {
    name: 'scdocs',
    version: 1,
    description: `${bundle.title} contract tools generated by scdocs.`,
    contracts: bundle.contracts.map((contract) => ({
      name: contract.name,
      id: contract.id,
      file: contract.file,
      summary: contract.summary,
      deployments: deploymentsOf(bundle, contract.id),
    })),
    tools,
  }
}

function toolName(contractName: string, fn: FunctionDoc): string {
  const suffix = fn.selector.slice(2, 6)
  return `${contractName}_${fn.name}_${suffix}`.replace(/[^A-Za-z0-9_]/g, '_')
}

function functionDescription(contractName: string, fn: FunctionDoc): string {
  const kind = isRead(fn) ? 'Read' : 'Write'
  return `${kind} ${contractName}.${fn.signature}${fn.summary ? ` — ${fn.summary}` : ''}`
}

function isRead(fn: FunctionDoc): boolean {
  return fn.mutability === 'view' || fn.mutability === 'pure'
}

function deploymentsOf(
  bundle: DocsBundle,
  contractId: string,
): Array<{ chainName: string; chainId: number; address: string }> {
  return bundle.chains.flatMap((chain) => {
    const address = chain.addresses[contractId]
    return address ? [{ chainName: chain.name, chainId: chain.chainId, address }] : []
  })
}
